// ── Tipo de claves ────────────────────────────────────────────────────────────
type TranslationKey = keyof typeof translations.es;
type Translations   = Record<TranslationKey, string>;

// ── Detección de idioma ───────────────────────────────────────────────────────
function detectLanguage(): AppLanguage {
  const locales = Localization.getLocales();
  if (!locales || locales.length === 0) return 'en';

  const raw = locales[0].languageCode?.toLowerCase() ?? 'en';

  const supported: AppLanguage[] = ['es', 'en', 'pt', 'fr', 'de', 'it', 'ja', 'zh', 'ko', 'ar'];
  if ((supported as string[]).includes(raw)) return raw as AppLanguage;

  // Fallbacks comunes
  if (raw.startsWith('zh')) return 'zh';
  if (raw === 'cn')         return 'zh';

  return 'en'; // fallback universal
}

// ── Estado global (singleton) ─────────────────────────────────────────────────
let currentLang: AppLanguage      = detectLanguage();
let currentStrings: Translations  = (translations as any)[currentLang] as Translations ?? translations.en as Translations;

// ── API pública ───────────────────────────────────────────────────────────────

/**
 * t — traduce una clave con soporte de interpolación.
 *
 * @example
 *   t('home_stat_countries', { n: 10 }) → '+10 países' (en español)
 *   t('home_stat_countries', { n: 10 }) → '+10 countries' (en inglés)
 */
export function t(key: TranslationKey, vars?: Record<string, string | number>): string {
  let str: string = currentStrings[key] ?? (translations.en as Translations)[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}

/**
 * getLanguage — devuelve el idioma activo.
 */
export function getLanguage(): AppLanguage {
  return currentLang;
}

/**
 * setLanguage — cambia el idioma manualmente (override del automático).
 * Útil para un selector de idioma en Settings.
 */
// ── Suscripción: React re-renderiza al cambiar de idioma ──────────────────────
const LANG_KEY = '@app_language';
const langListeners = new Set<() => void>();
function notifyLang() { langListeners.forEach((l) => l()); }

export function setLanguage(lang: AppLanguage): void {
  currentLang   = lang;
  currentStrings = (translations as any)[lang] as Translations ?? translations.en as Translations;
  AsyncStorage.setItem(LANG_KEY, lang).catch(() => {});
  notifyLang();
}

/** Carga el idioma elegido por el usuario (si lo guardó) al arrancar la app. */
export async function loadSavedLanguage(): Promise<void> {
  try {
    const saved = await AsyncStorage.getItem(LANG_KEY);
    if (saved && (translations as any)[saved]) setLanguage(saved as AppLanguage);
  } catch { /* usar el idioma del dispositivo */ }
}

/** Hook reactivo: el componente se re-renderiza cuando cambia el idioma. */
export function useLanguage(): AppLanguage {
  return useSyncExternalStore(
    (cb) => { langListeners.add(cb); return () => langListeners.delete(cb); },
    () => currentLang,
  );
}

/**
 * resetToDeviceLanguage — vuelve al idioma del teléfono.
 */
export function resetToDeviceLanguage(): void {
  setLanguage(detectLanguage());
}

